#!/usr/bin/env python3
"""
Build a REAL, held-out evaluation benchmark for the QA harness.

Why this exists: tests/fixtures/00EABED2_590_160/recording.csv is synthetic (generated by
scripts/generate_test_recording.py -- perfectly uniform 25 Hz, textbook sine waves). Scoring the
system on that measures how well it reads idealised signals, not in-the-wild ExtraSensory data,
and the brief explicitly values robustness on messy real data over clean-subset performance.

Two integrity rules this script enforces:
  1. Recordings are cut from REAL ExtraSensory bursts, keeping the real ~20 s-per-minute burst
     structure and the real gaps between them. Nothing is synthesised.
  2. Benchmark users come only from fold 0's TEST split, and --train-eval-model fits a Random
     Forest on fold 0's TRAIN split only. The shipped results/model_rf.joblib was fitted on all
     60 users, so scoring it against any ExtraSensory user would be scoring on training data.

Usage (on the machine holding data/):
    python scripts/build_eval_benchmark.py --probe
    python scripts/build_eval_benchmark.py --train-eval-model
    python scripts/build_eval_benchmark.py --build-recordings --n-users 15
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.preprocess.load import (CLASSES, load_folds, load_labels,  # noqa: E402
                                 read_burst, resample, to_g)

MINUTE_SEC = 60
ACTIVE = {"walking", "running", "bicycling"}


# --------------------------------------------------------------------------- recording assembly
def _burst_index(root: Path, kind: str, uuid: str) -> dict[int, Path]:
    """{minute_timestamp: file} for one modality, from a single directory scan."""
    d = next(iter((root / kind).rglob(uuid)), None)
    if d is None:
        return {}
    out = {}
    for p in d.iterdir():
        head = p.name.split(".")[0]
        if head.isdigit():
            out[int(head)] = p
    return out


def user_labelled_minutes(uuid: str, data_dir: str) -> list[tuple[int, str]]:
    """
    -> [(unix_ts, label)] for minutes that have BOTH raw bursts on disk, sorted by time.

    Deliberately reads no signal: only the label CSV plus two directory listings. Selection
    (pick_segment) only needs labels and timestamps, and reading every burst for every candidate
    user first made this step take longer than the rest of the pipeline combined.
    """
    root = Path(data_dir) / "raw"
    acc_idx = _burst_index(root, "raw_acc", uuid)
    gyr_idx = _burst_index(root, "raw_gyro", uuid)
    both = acc_idx.keys() & gyr_idx.keys()
    labels = load_labels(uuid, data_dir)
    out = [(int(ts), row["label"]) for ts, row in labels.iterrows()
           if int(ts) in both and row["label"] in CLASSES]
    out.sort()
    return out


def load_segment_bursts(uuid: str, data_dir: str, seg: list[tuple[int, str]]) -> list[tuple[int, str, np.ndarray]]:
    """Read raw signal for the chosen minutes only -> [(ts, label, (n,6) 25 Hz [acc g, gyro])]."""
    root = Path(data_dir) / "raw"
    acc_idx = _burst_index(root, "raw_acc", uuid)
    gyr_idx = _burst_index(root, "raw_gyro", uuid)
    out = []
    for ts, label in seg:
        a, g = read_burst(acc_idx[ts]), read_burst(gyr_idx[ts])
        if a is None or g is None:
            continue
        a, g = to_g(resample(a)), resample(g)
        n = min(len(a), len(g))
        if n < 25:                      # < 1 s of usable signal
            continue
        out.append((ts, label, np.hstack([a[:n], g[:n]])))
    return out


def pick_segment(mins: list, target_len: int, max_gap_min: int = 5) -> list:
    """
    Choose a contiguous-in-time run of `target_len` minutes that contains at least two distinct
    activities, preferring runs that include an active class so temporal questions aren't all
    sedentary. Runs are cut wherever the recording gap exceeds max_gap_min.
    """
    runs, cur = [], [mins[0]]
    for prev, nxt in zip(mins, mins[1:]):
        if nxt[0] - prev[0] <= max_gap_min * MINUTE_SEC:
            cur.append(nxt)
        else:
            runs.append(cur); cur = [nxt]
    runs.append(cur)

    best, best_score = None, -1.0
    for run in runs:
        for start in range(0, max(1, len(run) - target_len + 1), max(1, target_len // 3)):
            seg = run[start:start + target_len]
            if len(seg) < min(target_len, 30):
                continue
            labels = {r[1] for r in seg}
            if len(labels) < 2:
                continue
            # prefer: more distinct classes, presence of an active class, closer to target length
            score = len(labels) + (2.0 if labels & ACTIVE else 0.0) + len(seg) / (2.0 * target_len)
            if score > best_score:
                best, best_score = seg, score
    return best or []


def write_recording(seg: list, out_dir: Path) -> dict:
    """
    Lay each minute's real burst at its real offset; merge same-label minutes into truth intervals.

    Ground truth must be a clean, NON-OVERLAPPING partition or IoU scoring is ill-defined. Real
    ExtraSensory minute timestamps drift (61 s apart, not exactly 60), so a minute is clamped to
    end at the next minute's start rather than always start+60; and consecutive same-label minutes
    are merged when they actually abut, instead of requiring exact float equality.
    """
    t0 = seg[0][0]
    offs = [ts - t0 for ts, _, _ in seg]
    rows, truth = [], []
    for i, (ts, label, burst) in enumerate(seg):
        off = offs[i]
        t = off + np.arange(len(burst)) / 25.0
        rows.append(np.column_stack([t, burst]))
        nxt = offs[i + 1] if i + 1 < len(seg) else off + MINUTE_SEC
        end = min(float(nxt), float(off + MINUTE_SEC))      # never run into the next minute
        if truth and truth[-1]["activity"] == label and off - truth[-1]["end"] <= 5.0:
            truth[-1]["end"] = end                          # same activity, adjacent minute
        else:
            truth.append({"activity": label, "start": float(off), "end": end})

    arr = np.vstack(rows)
    df = pd.DataFrame(arr, columns=["timestamp", "acc_x", "acc_y", "acc_z", "gyro_x", "gyro_y", "gyro_z"])
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "recording.csv", index=False)
    (out_dir / "truth.json").write_text(json.dumps({"t0_unix": int(t0), "intervals": truth}, indent=1))

    dur = float(arr[-1, 0])
    counts = {}
    for iv in truth:
        counts[iv["activity"]] = counts.get(iv["activity"], 0.0) + iv["end"] - iv["start"]
    return {"minutes": len(seg), "samples": len(df), "span_sec": round(dur, 1),
            "n_intervals": len(truth), "class_seconds": {k: round(v) for k, v in sorted(counts.items())}}


# --------------------------------------------------------------------------- eval model
def train_eval_model(data_dir: str, features: str, out: Path, fold: int, trees: int) -> None:
    """RF fitted on fold `fold`'s TRAIN users only -> an honestly held-out model for benchmarking."""
    import joblib
    from sklearn.ensemble import RandomForestClassifier
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from scripts.train_classifier import ACTIVE as ACTIVE_IDX, CONTEXT, STILL_G, aggregate_minutes, feature_mask

    d = np.load(features, allow_pickle=True)
    X, y, uuid, ts, names = d["X"], d["y"], d["uuid"].astype(str), d["ts"], d["names"]
    X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)
    mask = feature_mask(names, "noori")
    still_col = list(map(str, names)).index("acc_mag__std")

    Xs, ys, us, tss, still = aggregate_minutes(X, y, uuid, ts, still_col)
    Xs = Xs[:, np.concatenate([mask, mask])]
    consistent = ~(np.isin(ys, list(ACTIVE_IDX)) & (still < STILL_G))

    folds = load_folds(data_dir)
    tr_users = set(folds[fold]["train"])
    tr = np.isin(us, list(tr_users)) & consistent
    print(f"fold {fold}: fitting RF on {tr.sum()} minutes from {len(set(us[tr]))} TRAIN users "
          f"(held-out test users: {len(folds[fold]['test'])})", flush=True)

    t0 = time.time()
    model = RandomForestClassifier(n_estimators=trees, min_samples_leaf=3,
                                   class_weight="balanced_subsample", n_jobs=-1, random_state=0).fit(Xs[tr], ys[tr])
    print(f"fitted in {time.time()-t0:.0f}s", flush=True)

    bundle = {"model": model, "feature_names": [str(n) for n in names], "mask": mask, "level": "minute",
              "context": CONTEXT, "classes": CLASSES, "subset": "noori", "cleaned": True,
              "still_g": STILL_G, "eval_fold": fold, "kind": "sklearn",
              "note": f"trained on fold {fold} TRAIN users only; safe to evaluate on fold {fold} test users"}
    out.parent.mkdir(exist_ok=True)
    joblib.dump(bundle, out, compress=3)
    print(f"saved {out} ({out.stat().st_size/1e6:.1f} MB)", flush=True)


# --------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default="data")
    ap.add_argument("--features", default="data/processed/features.npz")
    ap.add_argument("--fold", type=int, default=0)
    ap.add_argument("--out-dir", default="data/eval_benchmark")
    ap.add_argument("--n-users", type=int, default=15)
    ap.add_argument("--minutes", type=int, default=120, help="target recording length in minutes")
    ap.add_argument("--trees", type=int, default=300)
    ap.add_argument("--probe", action="store_true")
    ap.add_argument("--train-eval-model", action="store_true")
    ap.add_argument("--build-recordings", action="store_true")
    ap.add_argument("--model-out", default="results/model_rf_fold0.joblib")
    args = ap.parse_args()

    folds = load_folds(args.data_dir)
    test_users = folds[args.fold]["test"]
    print(f"fold {args.fold}: {len(folds[args.fold]['train'])} train users / {len(test_users)} test users")

    if args.probe:
        print("\nprobing held-out test users for usable material (labels only, no signal read)...")
        for u in test_users:
            t0 = time.time()
            mins = user_labelled_minutes(u, args.data_dir)
            if not mins:
                print(f"  {u}: no usable minutes", flush=True); continue
            labs = {}
            for _, l in mins:
                labs[l] = labs.get(l, 0) + 1
            seg = pick_segment(mins, args.minutes)
            seg_labs = sorted({l for _, l in seg})
            span = (mins[-1][0] - mins[0][0]) / 3600
            print(f"  {u}: {len(mins)} min over {span:.1f}h, classes={labs}, "
                  f"best_segment={len(seg)} min {seg_labs} ({time.time()-t0:.0f}s)", flush=True)
        return

    if args.train_eval_model:
        train_eval_model(args.data_dir, args.features, Path(args.model_out), args.fold, args.trees)

    if args.build_recordings:
        out_root = Path(args.out_dir)
        built = {}
        for u in test_users:
            if len(built) >= args.n_users:
                break
            mins = user_labelled_minutes(u, args.data_dir)
            if not mins:
                continue
            chosen = pick_segment(mins, args.minutes)
            if len(chosen) < 30:
                print(f"  {u}: skipped (best segment only {len(chosen)} min)", flush=True)
                continue
            seg = load_segment_bursts(u, args.data_dir, chosen)   # signal read for these minutes only
            if len(seg) < 30:
                print(f"  {u}: skipped ({len(seg)} minutes survived signal read)", flush=True)
                continue
            info = write_recording(seg, out_root / u)
            built[u] = info
            print(f"  {u}: {info}", flush=True)
        (out_root / "index.json").write_text(json.dumps(
            {"fold": args.fold, "source": "ExtraSensory real bursts, held-out fold test users",
             "recordings": built}, indent=1))
        print(f"\nbuilt {len(built)} real recordings -> {out_root}")


if __name__ == "__main__":
    main()
